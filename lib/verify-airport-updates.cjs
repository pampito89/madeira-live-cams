const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
require.extensions['.ts'] = (mod, file) => mod._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, file);
const { parseAirportNews, parseAirportWarnings } = require('./airportUpdates.ts');
const { airportUpdatesText } = require('./i18n/airportUpdates.ts');
const now = Date.parse('2026-10-19T12:00:00Z');
const item = (title, date, url='https://pt.newsroom.ana.pt/news/test.html') => `<item><title><![CDATA[${title}]]></title><pubDate>${date}</pubDate><link>${url}</link></item>`;
const rss = text => `<rss><channel>${text}</channel></rss>`;
const fresh='2026-10-19T10:00:00Z';
assert.equal(parseAirportNews(rss(item('Madeira aviso',fresh)),now).length,1);
assert.equal(parseAirportNews(rss(item('Lisboa aviso',fresh)),now).length,0);
assert.equal(parseAirportNews(rss(item('Madeira old','2025-10-01')),now).length,0);
assert.equal(parseAirportNews(rss(item('Madeira future','2026-10-20')),now).length,0);
assert.equal(parseAirportNews(rss(item('Madeira unsafe',fresh,'javascript:alert(1)')),now).length,0);
assert.throws(()=>parseAirportNews('<html>Error</html>',now));
const warning = { idAreaAviso:'MCS', awarenessTypeName:'Vento', awarenessLevelID:'orange',startTime:'2026-10-19T10:00:00',endTime:'2026-10-19T18:00:00' };
assert.equal(parseAirportWarnings([warning],now)[0].start,'2026-10-19T10:00:00.000Z');
assert.equal(parseAirportWarnings([{...warning,awarenessLevelID:'green'}],now).length,0);
assert.throws(()=>parseAirportWarnings([{...warning,idAreaAviso:'MCN'}],now));
assert.throws(()=>parseAirportWarnings([{...warning,endTime:'2026-10-19T11:00:00'}],now));
assert.equal(parseAirportWarnings([warning,{...warning,endTime:'2026-10-19T11:00:00'}],now).length,1);
for(const locale of ['en','uk','pt','de','fr','es','pl']) { const t=airportUpdatesText(locale); assert.ok(t.heading); assert.ok(t.type('Vento')); assert.ok(t.level('red')); }
console.log('PASS: official news filtering, date expiry, unsafe URLs, invalid feeds, UTC warning times, south-coast scope, unavailable versus empty and seven languages.');
