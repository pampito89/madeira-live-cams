const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
require.extensions['.ts']=(mod,file)=>mod._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,file);
const {filterEvents,selectRangeDay,monthDays,shiftMonth}=require('./events.ts');
const base={title:'Event',description:'',venue:'Funchal',municipalities:['Funchal'],category:'Music'};
const events=[{...base,id:'long',start:'2026-10-20',end:'2026-11-05'},{...base,id:'one',start:'2026-11-01',end:'2026-11-01'},{...base,id:'later',start:'2026-11-06',end:'2026-11-08'},{...base,id:'past',start:'2026-10-01',end:'2026-10-02'}];
const filter=(from,to,extra={})=>filterEvents(events,{today:'2026-10-26',dateRange:{from,to},...extra}).map(e=>e.id);
assert.deepEqual(filter('2026-11-01','2026-11-01'),['long','one']);
assert.deepEqual(filter('2026-11-05','2026-11-06'),['long','later']);
assert.deepEqual(filter('2026-11-06','2026-11-05'),['long','later']);
assert.deepEqual(filter('2026-11-09','2026-11-10'),[]);
assert.deepEqual(filter('2026-11-01',''),['long','one']);
assert.deepEqual(filter('',''),['long','one','later']);
assert.deepEqual(filter('2026-10-01','2026-10-02'),[]);
assert.deepEqual(filter('2026-11-01','2026-11-05',{municipality:'Machico'}),[]);
assert.deepEqual(filter('2026-11-01','2026-11-05',{category:'Food'}),[]);
const first=selectRangeDay({from:'',to:''},'2026-12-31',false);
assert.deepEqual(first,{range:{from:'2026-12-31',to:'2026-12-31'},choosingEnd:true});
assert.deepEqual(selectRangeDay(first.range,'2027-01-02',true).range,{from:'2026-12-31',to:'2027-01-02'});
assert.deepEqual(selectRangeDay(first.range,'2026-12-28',true).range,{from:'2026-12-28',to:'2026-12-31'});
assert.deepEqual(selectRangeDay(first.range,'2026-12-31',true),{range:first.range,choosingEnd:false});
assert.deepEqual(selectRangeDay(first.range,'2027-02-01',false).range,{from:'2027-02-01',to:'2027-02-01'});
assert.equal(monthDays('2028-02').filter(Boolean).length,29);
assert.equal(shiftMonth('2026-12',1),'2027-01');
console.log('PASS: one day, inclusive overlap, reversed range, cross-month/year selection, empty state, reset and combined filters.');
