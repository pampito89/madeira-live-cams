const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true, resolveJsonModule: true } }).outputText, filename);
const api = require('./operationalNews.ts');
const site = require('./siteNews.ts');
const seed = require('../data/operational-news-seed.json');
const catalog = require('../data/operational-news-uk.json');
assert.equal(api.allowedOperationalUrl('https://evil.example/pt/?view=article&id=640&catid=146'), false);
assert.equal(api.allowedOperationalUrl('https://ifcn.madeira.gov.pt.evil.example/pt/?view=article&id=640&catid=146'), false);
assert.equal(api.allowedOperationalUrl('http://ifcn.madeira.gov.pt/pt/?view=article&id=640&catid=146'), false);
assert.equal(api.elementBody('<div class="body">one<div>two</div>three</div>outside', /<div class="body">/), 'one<div>two</div>three');
for (const [id, edited] of Object.entries(catalog)) {
  const original = seed.articles.find(item => item.id === id);
  assert.ok(original, id);
  assert.equal(api.sourceFingerprint(original), edited.fingerprint, id);
  assert.equal(site.editedOperational(original).contentLanguage, 'uk');
  assert.equal(site.editedOperational({ ...original, paragraphs: ['Changed announcement'] }), null);
}
const ifcn = seed.articles.find(item => item.id === 'ifcn-1014');
assert.equal(ifcn.publishedAt, null);
assert.ok(site.editedOperational(ifcn).paragraphs.some(text => text.includes('не вказано')));
assert.equal(site.newsCategory('roads'), 'roads');
assert.equal(site.newsCategory('__proto__'), 'all');
assert.equal(site.newsCategory(['roads']), 'all');
const parsed = api.parseOperationalArticle('<title>Encerramento</title><div class="astroid-article-text"><p>O percurso está encerrado temporariamente por motivos de segurança.</p><div><p>Reabertura será comunicada.</p></div></div><p>outside</p>', ifcn.sourceUrl, '2026-11-08T10:00:00Z');
assert.equal(parsed.publishedAt, null);
assert.ok(!parsed.paragraphs.includes('outside'));
assert.throws(() => api.parseOperationalArticle('<div>changed layout</div>', ifcn.sourceUrl, '2026-11-08T10:00:00Z'));
console.log('Operational news: source validation, nested parsing, dates, translation invalidation and filters passed.');
