require('./operational-news.test.cjs');
const assert=require('node:assert/strict');
const {allowedTrailPolicyUrl,policyTopic,discoverTrailPolicies,parseTrailPolicy}=require('./trailPolicyNews.ts');
const seed=require('../data/trail-policy-seed.json').articles[0];
assert.equal(allowedTrailPolicyUrl(seed.sourceUrl),true);
for(const url of ['http://madeira.rtp.pt/sociedade/taxas/','https://madeira.rtp.pt.evil.example/sociedade/taxas/','https://madeira.rtp.pt/sociedade/taxas/?url=evil','https://user@madeira.rtp.pt/sociedade/taxas/']) assert.equal(allowedTrailPolicyUrl(url),false);
assert.equal(policyTopic('Novas regras de reserva nos percursos pedestres'),true);
assert.equal(policyTopic('Taxas de aeroporto'),false);
assert.equal(policyTopic('Percursos fechados devido a chuva'),false);
const html=`<h1 class="main-article-title">${seed.title}</h1><p class="main-article-lead">${seed.paragraphs[0]}</p><span class="main-article-date-info float-right">10 nov, 2026, 14:02</span><div class="article-content">Do not copy the body</div>`;
const parsed=parseTrailPolicy(html,seed.sourceUrl,seed.checkedAt);
assert.deepEqual(parsed,seed);
assert.deepEqual(discoverTrailPolicies(`<a href="${seed.sourceUrl}">${seed.title}</a><a href="${seed.sourceUrl}">duplicate</a><a href="https://evil.example/sociedade/taxas-percursos/">taxas percursos</a>`),[seed.sourceUrl]);
assert.throws(()=>parseTrailPolicy('<h1>Changed layout</h1>',seed.sourceUrl,seed.checkedAt));
assert.throws(()=>parseTrailPolicy(html.replace('10 nov','31 fev'),seed.sourceUrl,seed.checkedAt));
console.log('Trail policy source: allowlist, topical discovery, deduplication, lead-only extraction, dates and seed passed.');
